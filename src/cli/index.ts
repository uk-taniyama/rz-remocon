import "./fetch-patch";
import fs from "node:fs";
import { Command } from "commander";
import { keyCodeSchema } from "../api";
import type { GenExport, GenerateFromFileOpts } from "../gen/types.js";
import {
  confirmConnection,
  createFileConfigStore,
  getPublicSupport,
  getSupport,
  getToken,
  type RegzaConfig,
  requestConnection,
  sendKeyCode,
  setRegzaConfigStore,
} from "../lib";
import { freezeRegzaConfig } from "../lib/regza-client";
import { randomUserId } from "../lib/utils";
import {
  commandDefaultColorMap,
  type DefaultColorMapCommandOpts,
} from "./color-map";
import { commandIconUrls, type IconUrlsCommandOpts } from "./icon-urls";
import { setupServer } from "./server";

/** `setup` コマンド。REGZA に接続を要求し、REGZA に PIN を表示させる。 */
export async function commandSetup(host: string): Promise<void> {
  const userId = randomUserId();

  console.log(`TV      : ${host}`);
  console.log(`user_id : ${userId}`);
  console.log();
  console.log("TVへ接続要求を送信しています...");

  await requestConnection(host, userId);
  console.log("REGZAにPINが表示されています。");
  console.log("confirm <pin>で設定してください。");
}

/** `confirm` コマンド。REGZA に表示された PIN を使用して、接続を確定する。 */
async function commandConfirm(pin: string): Promise<void> {
  if (!/^\d{4}$/.test(pin)) {
    throw new Error("PINは4桁の数字です。");
  }

  console.log("PINを確認しています...");
  await confirmConnection(pin);

  console.log("接続が完了しました。");
}

/** `support` コマンド。REGZA がサポートするコマンドの一覧を、`support.jsonl` に保存する。 */
async function commandSupport(): Promise<void> {
  const supportResponse = await getSupport();
  const jsonl = supportResponse.command
    .map((cmd) => JSON.stringify(cmd))
    .join("\n");
  console.log("support.jsonlに保存しました。");
  fs.writeFileSync("support.jsonl", `${jsonl}\n`, { mode: 0o600 });
}

/** `key` コマンド。指定したキーコードを REGZA に送信する。 */
async function commandKey(value: string): Promise<void> {
  const code = keyCodeSchema.parse(value);
  await freezeRegzaConfig();
  const token = await getToken();
  const response = await sendKeyCode(code, token);
  console.log(response);
}

/** `status` コマンド。REGZA の公開サポート API のレスポンスを表示する。 */
async function commandStatus(): Promise<void> {
  const support = await getPublicSupport();
  console.log(support);
}

async function main() {
  setRegzaConfigStore(
    createFileConfigStore<RegzaConfig>("./regza.json", {
      notFoundMessage: "regza.json がありません。先に setup してください。",
    }),
  );
  const program = new Command();

  program
    .name("rz-remocon")
    .description("REGZA remote controller")
    .version("1.0.0");

  program
    .command("setup")
    .description("Register this client with REGZA")
    .argument("<ip>", "REGZA IP address")
    .action(async (ip: string) => {
      await commandSetup(ip);
    });

  program
    .command("confirm")
    .description("Confirm connection with REGZA")
    .argument("<pin>", "REGZA PIN code")
    .action(async (pin: string) => {
      await commandConfirm(pin);
    });

  program
    .command("support")
    .description("Show supported REGZA APIs")
    .action(async () => {
      await commandSupport();
    });

  program
    .command("key")
    .description("Send a remote key")
    .argument("<keycode>", "key code")
    .action(async (keycode: string) => {
      await commandKey(keycode);
    });

  program
    .command("status")
    .description("Show REGZA connection status")
    .action(async () => {
      await commandStatus();
    });

  program
    .command("generate")
    .description("Generate static remote")
    .option(
      "-i, --input-json <path>",
      "Input remocon.json",
      "data/remocon.json",
    )
    .option("-o, --output-dir <path>", "Output directory", "output")
    .option(
      "--icon-urls <path>",
      "icon-urls.json (default: icon-urls.json next to the input)",
    )
    .action(async (options: GenerateFromFileOpts) => {
      // @ts-expect-error gen.js is generated by tsup
      const gen = (await import("./gen.js")) as GenExport;
      await gen._generateFromFile(options);
    });

  program
    .command("sample-icon-urls-from-google-favicons")
    .description(
      "Create icon-urls.json from Google favicons, and a preview HTML (personal sample)",
    )
    .option("-o, --output-dir <path>", "Output directory", "data")
    .option(
      "-d, --domains <path>",
      "Name-to-domain table (default: app-domains.json in the output directory; built-in list if missing)",
    )
    .option("-s, --size <px>", "Favicon size", "128")
    .action((options: IconUrlsCommandOpts) => {
      commandIconUrls(options);
    });

  program
    .command("default-color-map")
    .description(
      "Write the default color map to color-map.json, which you can edit",
    )
    .option("-o, --output-dir <path>", "Output directory", "data")
    .option("-f, --force", "Overwrite an existing color-map.json")
    .action((options: DefaultColorMapCommandOpts) => {
      commandDefaultColorMap(options);
    });

  setupServer(program);
  // process.env.NODE_TLS_REJECT_UNAUTHORIZED = "0";
  await program.parseAsync(process.argv);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
